import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const snapshot=JSON.parse(await readFile(new URL('../dist/snapshot.json',import.meta.url),'utf8'));
const html=await readFile(new URL('../dist/index.html',import.meta.url),'utf8');
for(const asset of ['style.css','app.js','assets/marked.js','assets/purify.js','assets/logo.svg','assets/dashboard-dark.png'])await readFile(new URL('../dist/'+asset,import.meta.url));
const elements={'#component':{value:'server'},'#platform':{value:'all'},'#downloads':{innerHTML:''}};
const context=vm.createContext({URL,console,document:{querySelector:s=>elements[s]}});
const source=await readFile(new URL('../dist/app.js',import.meta.url),'utf8');
vm.runInContext(source.split("$('#docs-search').addEventListener")[0],context);
context.snapshotData=snapshot;
vm.runInContext('release=snapshotData.release',context);
const pages=vm.runInContext("parseCatalog(snapshotData.docs['docs/README.md'])",context);
assert.ok(pages.length>=18);
for(const page of pages){const path=vm.runInContext(`docPath(${JSON.stringify(page.path)})`,context);assert.ok(snapshot.docs[path],`Missing fallback for ${path}`);assert.ok(vm.runInContext(`allowedPath(${JSON.stringify(path)})`,context));}
assert.equal(vm.runInContext("allowedPath('secrets.env')",context),false);
assert.equal(vm.runInContext("docPath('../CHANGELOG.md')",context),'CHANGELOG.md');
vm.runInContext('renderDownloads()',context);
assert.ok(elements['#downloads'].innerHTML.includes('sentrel-server-linux-amd64'));
assert.ok(!elements['#downloads'].innerHTML.includes('sentrel-agent-linux'));
elements['#component'].value='agent';elements['#platform'].value='windows';
vm.runInContext('renderDownloads()',context);
assert.ok(elements['#downloads'].innerHTML.includes('.msi'));
assert.ok(!elements['#downloads'].innerHTML.includes('linux-amd64'));
elements['#component'].value='server';vm.runInContext('renderDownloads()',context);
assert.ok(elements['#downloads'].innerHTML.includes('No matching assets'));
elements['#component'].value='other';elements['#platform'].value='all';vm.runInContext('renderDownloads()',context);
assert.ok(elements['#downloads'].innerHTML.includes('SHA256SUMS.sig'));
assert.equal(vm.runInContext("escapeHTML('<script>')",context),'&lt;script&gt;');
for(const match of html.matchAll(/href="#([a-z][a-z-]*)"/g))assert.ok(html.includes(`id="${match[1]}"`),`Missing anchor ${match[1]}`);
console.log(`Passed: ${pages.length} documentation routes, bundled assets, download filters, verification files and section links.`);

assert.ok(!/PolyForm|US\$1|commercial-enquiry|pricing\.js/.test(html),'Removed licensing and pricing must not remain');
assert.ok(html.includes('Apache License 2.0'));
console.log('Passed: Apache 2.0 messaging and removal of commercial plans.');
